"""Build message catalogs for MC5's TCP channels from a Ghidra decompilation export of the player's own libMC5.so.

Input: the directory written by ExportAll.java (decomp/XXXX.c files, functions.tsv) and, for the in-match receive
dispatcher, a separate long-timeout decompile of it. Output: Markdown tables on stdout.
No game code or data is stored; the tables only list message types, field types and Ghidra addresses.

usage: python3 -I catalog.py <export_dir> <match_dispatcher.c> > catalog.md
"""
import os, re, sys

READ = {'009cf3d8': 'u8', '009cf4c0': 'u16', '009cf5a0': 'u32', '009cf858': 'f32', '009cf708': 'u64',
        '009cfe10': 'str', '009cfa28': 'bytes(n)', '009cfaa0': 'bytes(n)', '009cfd50': 'bytes32',
        '009cfcb8': 'blob32', '00d090e8': 'lz4blob', '00cf7230': 'lz4blob'}
WRITE = {'009cf3a8': 'u8', '009cf470': 'u16', '009cf520': 'u32', '009cf7d0': 'f32', '009cf628': 'u64',
         '009cf8c8': 'f64', '009cf9b0': 'raw', '009cfae0': 'bytes16', '009cfc20': 'bytes32', '009cfdd8': 'str'}
CALL = re.compile(r'(?:thunk_)?FUN_([0-9a-f]{8})\(')
STR = re.compile(r'"([^"\\]{3,48})"')

def load(export):
    funcs = {}
    d = os.path.join(export, 'decomp')
    for fn in os.listdir(d):
        txt = open(os.path.join(d, fn), encoding='utf-8', errors='replace').read()
        for block in txt.split('// ==== FUNC ')[1:]:
            head = block.split('\n', 1)[0]
            funcs[head.rsplit('@ ', 1)[-1].strip()] = block
    return funcs

def seq(body, table):
    return [table[c] for c in CALL.findall(body) if c in table]

def char_case(lbl):
    lbl = lbl.strip()
    m = re.match(r"'\\x([0-9a-f]{2})'", lbl)
    if m: return int(m.group(1), 16)
    m = re.match(r"'\\([abtnvfr0'\"\\])'", lbl)
    if m: return {'a': 7, 'b': 8, 't': 9, 'n': 10, 'v': 11, 'f': 12, 'r': 13, '0': 0, "'": 39, '"': 34, '\\': 92}[m.group(1)]
    m = re.match(r"'(.)'", lbl)
    if m: return ord(m.group(1))
    try: return int(lbl, 0) & 0xff
    except ValueError: return None

def split_cases(body):
    out, cur, labels = {}, [], []
    for line in body.split('\n'):
        m = re.match(r"\s*case (.+?):\s*$", line)
        if m:
            if cur and labels:
                for l in labels: out.setdefault(l, []).extend(cur)
                labels, cur = [], []
            v = char_case(m.group(1))
            if v is not None: labels.append(v)
            continue
        if labels: cur.append(line)
    if cur and labels:
        for l in labels: out.setdefault(l, []).extend(cur)
    return {k: '\n'.join(v) for k, v in out.items()}

def main(export, match_c):
    funcs = load(export)
    print('# MC5 TCP message catalog (generated)\n')
    print('Generated by `tools/protocol-catalog/catalog.py` from a Ghidra export of libMC5.so 6.0.12a. Addresses are '
          'Ghidra addresses (ELF + 0x100000). Field lists are the order of primitive reads or writes in the code; '
          'conditional fields and loops appear inline, so treat them as a starting point, not a final layout.\n')
    print('Primitives: u8/u16/u32/u64 big-endian, f32/f64, `str` = u16 length + bytes, `bytes16`/`bytes32` = '
          'u16/u32 length + bytes, `blob32` = u32 length + bytes, `lz4blob` = u32 length + LZ4 block (decompressed '
          'to at most 1 MB, NUL-terminated text).\n')
    for name, addr in (('Meta channel, server to client (dispatcher G:0xd09780)', '00d09780'),
                       ('Meta channel, server to client (dispatcher G:0xcf72d0)', '00cf72d0')):
        cases = split_cases(funcs.get(addr, ''))
        print(f'## {name}\n\n| Type | Reads (in order) | Strings |\n|---|---|---|')
        for t in sorted(cases):
            b = cases[t]
            print(f"| 0x{t:02x} | {' '.join(seq(b, READ)[:16]) or '-'} | {', '.join(dict.fromkeys(STR.findall(b)))[:120]} |")
        print()
    # builders: any function that begins a message with FUN_009cfe60(writer, type, ...)
    rows = []
    for addr, b in funcs.items():
        for m in re.finditer(r'FUN_009cfe60\([^,]+,(0x[0-9a-f]+|\d+),', b):
            rows.append((int(m.group(1), 0), addr, seq(b, WRITE)))
            break
    meta = [r for r in rows if r[1] >= '00cf0000']
    match = [r for r in rows if r[1] < '00cf0000']
    for title, rs in (('Meta channel, client to server (builders)', meta), ('In-match, client to peers/server (builders)', match)):
        print(f'## {title}\n\n| Type | Builder | Writes (in order) |\n|---|---|---|')
        for t, a, s in sorted(rs):
            print(f"| 0x{t:02x} | G:0x{a.lstrip('0')} | {' '.join(s[:18]) or '-'} |")
        print()
    # in-match receive dispatcher: case -> FUN_00bc47e0(type) object, parse function
    txt = open(match_c, encoding='utf-8', errors='replace').read()
    body = txt.split('// ==== FUNC ')[1] if '// ==== FUNC ' in txt else txt
    cases = split_cases(body)
    print('## In-match, received (dispatcher G:0xbe5fd8)\n\n| Type | Parse function | Reads in parser | Authority-gated |\n|---|---|---|---|')
    for t in sorted(cases):
        if t < 0x0b:
            continue  # the dispatcher handles 0x0b..0xe7; lower labels come from nested switches
        b = cases[t]
        m = re.search(r'FUN_00bc47e0\((0x[0-9a-f]+|\d+)\);\s*\n\s*(?:thunk_)?FUN_([0-9a-f]{8})\(', b)
        parser = m.group(2) if m else ''
        reads = ' '.join(seq(funcs.get(parser, ''), READ)[:14]) if parser else ''
        gated = 'yes' if 'FUN_00bc02c0' in b else ''
        print(f"| 0x{t:02x} | {('G:0x' + parser.lstrip('0')) if parser else '-'} | {reads or '-'} | {gated} |")
    print()

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
